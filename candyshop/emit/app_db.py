"""Source 1 - the application database (PostgreSQL).

Writes `data/app_db/schema.sql` + `data/app_db/seed.sql` (COPY blocks, loaded by docker-compose's
postgres init) and can load the same rows straight into a running Postgres.
"""
from __future__ import annotations

import json
import re
from datetime import date, datetime
from decimal import Decimal
from importlib import resources
from pathlib import Path

from ..sim.world import World

# table -> (world table name, ordered column list). Order = foreign-key load order.
APP_TABLES: dict[str, tuple[str, list[str]]] = {
    "plans": ("app_plans", ["plan_id", "name", "monthly_price_cents", "annual_price_cents", "lead_limit", "campaign_limit", "seat_limit"]),
    "products": ("app_products", ["product_id", "sku", "name", "category", "list_price", "unit_cost", "season"]),
    "accounts": ("app_accounts", ["account_id", "name", "slug", "plan_id", "status", "signup_source", "shop_type", "city", "state",
                                  "postal_code", "timezone", "employees", "billing_customer_id", "created_at", "trial_ends_at",
                                  "churned_at", "churn_reason", "merged_into_account_id", "deleted_at", "settings", "updated_at"]),
    "users": ("app_users", ["user_id", "account_id", "email", "full_name", "role", "is_active", "created_at", "last_login_at", "updated_at"]),
    "leads": ("app_leads", ["lead_id", "account_id", "assigned_user_id", "org_name", "contact_name", "lead_type", "source", "city",
                            "state", "postal_code", "score", "status", "est_order_value", "notes", "created_at", "updated_at", "attributes"]),
    "campaigns": ("app_campaigns", ["campaign_id", "account_id", "created_by_user_id", "name", "channel", "season_tag", "status",
                                    "audience_size", "delivered", "opens", "clicks", "unsubscribes", "sent_at", "created_at",
                                    "audience_filter"]),
    "orders": ("app_orders", ["order_id", "account_id", "lead_id", "campaign_id", "ordered_at", "order_type", "channel", "status",
                              "subtotal", "discount", "total", "item_count", "updated_at"]),
    "order_items": ("app_order_items", ["order_item_id", "order_id", "product_id", "quantity", "unit_price"]),
    "exit_surveys": ("app_exit_surveys", ["survey_id", "account_id", "submitted_at", "reason_code", "would_recommend", "free_text"]),
    "nps_responses": ("app_nps", ["response_id", "account_id", "user_id", "submitted_at", "score", "comment"]),
}


def schema_sql() -> str:
    return resources.files("candyshop.emit").joinpath("app_schema.sql").read_text()


def _cell(v) -> str:
    """Render a value in PostgreSQL COPY text format."""
    if v is None:
        return r"\N"
    if isinstance(v, bool):
        return "t" if v else "f"
    if isinstance(v, datetime):
        return v.strftime("%Y-%m-%d %H:%M:%S+00")
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, (dict, list)):
        v = json.dumps(v, separators=(",", ":"), sort_keys=True)
    elif isinstance(v, (float, Decimal)):
        v = f"{v:.2f}"
    s = str(v)
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def rows(w: World, table: str):
    wt, cols = APP_TABLES[table]
    pk = cols[0]
    for row in sorted(w.t[wt].values(), key=lambda r: r[pk]):
        yield [row.get(c) for c in cols]


def write_seed(w: World, out_dir: Path) -> dict[str, int]:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "schema.sql").write_text(schema_sql())
    counts = {}
    with open(out_dir / "seed.sql", "w", encoding="utf-8") as fh:
        fh.write("-- Generated by `candy init` / `candy grow`. Do not edit by hand.\nSET search_path = app;\nSET client_encoding = 'UTF8';\n\n")
        for table, (_wt, cols) in APP_TABLES.items():
            n = 0
            fh.write(f"COPY app.{table} ({', '.join(cols)}) FROM stdin;\n")
            for r in rows(w, table):
                fh.write("\t".join(_cell(v) for v in r) + "\n")
                n += 1
            fh.write("\\.\n\n")
            counts[table] = n
    return counts


def _stamp(cur, w: World) -> None:
    """Record which data date this database holds, readable by `candy status`."""
    cur.execute(f"COMMENT ON SCHEMA app IS 'candy as_of={w.clock.isoformat()} seed={int(w.seed)}'")


def db_as_of(url: str) -> str | None:
    """The data date a live database holds, or None if it has no candy data / is unreachable."""
    import psycopg
    try:
        with psycopg.connect(url, connect_timeout=2) as conn:
            row = conn.execute("SELECT obj_description('app'::regnamespace)").fetchone()
    except Exception:
        return None
    m = re.search(r"as_of=(\S+)", row[0] or "") if row else None
    return m.group(1) if m else None


def sync_postgres(w: World, url: str, reset: bool = False) -> dict[str, int]:
    """Bring a live database up to date without dropping it: new rows are inserted, changed rows updated.

    Falls back to a full (re)load when the schema does not exist yet or `reset` is set.
    Returns the row count of each table afterwards.
    """
    import psycopg

    with psycopg.connect(url, connect_timeout=3) as conn:
        exists = conn.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name = 'app'").fetchone()
    if reset or not exists:
        return load_postgres(w, url)
    counts = {}
    with psycopg.connect(url, autocommit=False) as conn, conn.cursor() as cur:
        for table, (_wt, cols) in APP_TABLES.items():
            cur.execute("DROP TABLE IF EXISTS _candy_stage")
            cur.execute(f"CREATE TEMP TABLE _candy_stage (LIKE app.{table} INCLUDING DEFAULTS)")
            with cur.copy(f"COPY _candy_stage ({', '.join(cols)}) FROM STDIN") as cp:
                for r in rows(w, table):
                    cp.write("\t".join(_cell(v) for v in r) + "\n")
            updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols[1:])
            cur.execute(f"INSERT INTO app.{table} ({', '.join(cols)}) SELECT {', '.join(cols)} FROM _candy_stage "
                        f"ON CONFLICT ({cols[0]}) DO UPDATE SET {updates}")
            cur.execute(f"SELECT count(*) FROM app.{table}")
            counts[table] = cur.fetchone()[0]
        _stamp(cur, w)
        conn.commit()
    return counts


def load_postgres(w: World, url: str) -> dict[str, int]:
    """(Re)create the `app` schema in the target database and bulk-load every table."""
    import psycopg

    counts = {}
    with psycopg.connect(url, autocommit=False) as conn:
        with conn.cursor() as cur:
            cur.execute(schema_sql())
            for table, (_wt, cols) in APP_TABLES.items():
                n = 0
                with cur.copy(f"COPY app.{table} ({', '.join(cols)}) FROM STDIN") as cp:
                    for r in rows(w, table):
                        cp.write("\t".join(_cell(v) for v in r) + "\n")
                        n += 1
                counts[table] = n
            _stamp(cur, w)
        conn.commit()
    return counts
